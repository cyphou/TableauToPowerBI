"""Executable model of the PySpark behaviour the Fabric converter relies on.

This is a MODEL, not Spark.  It was written from the PySpark documentation and,
for ``Column.substr``, from Spark's ``UTF8String.substringSQL``.  Nothing here
was compared with a real Spark session, so a test built on it shows that the
generated code means what the hand-written Tableau reference in that test says
*under these documented rules*; it does not show that Spark agrees.

It reproduces the Python-level traps of the Column API, which the generated
code must never fall into:

* ``bool(Column)`` raises, so ``and``, ``or``, ``not`` and chained comparisons
  fail;
* ``int(Column)`` is a TypeError;
* a bare Python string passed where a Column is expected is read as a column
  NAME, and a bare number is a TypeError;
* ``Column.otherwise`` cannot be applied twice and ``Column.substr`` takes two
  integers or two Columns, never a mix.

and Spark's NULL rules with ANSI mode off: a NULL operand gives NULL, ``/`` by
zero gives NULL, ``&``/``|`` are three-valued, ``F.concat`` is NULL when any
input is NULL, an out-of-range ``getItem`` is NULL.
"""

import datetime as dt
import math
import operator
import re
from decimal import ROUND_HALF_UP, Decimal, InvalidOperation

TODAY = dt.date(2024, 3, 15)
NOW = dt.datetime(2024, 3, 15, 10, 30, 45)
NAN = float('nan')


class Row:
    """A case-insensitive row; an unknown column raises as Spark's analyser would."""

    def __init__(self, values):
        self._values = {str(key).casefold(): value for key, value in values.items()}

    def get(self, name):
        try:
            return self._values[name.casefold()]
        except KeyError:
            raise KeyError(f'cannot resolve column {name!r}') from None


class _Case:
    """State of a ``when(...)`` chain: its branches and whether ``otherwise`` closed it."""

    def __init__(self, branches, closed):
        self.branches = branches
        self.closed = closed


class Col:
    """A lazily evaluated column expression; ``reads`` lists the columns it names."""

    def __init__(self, fn, reads=(), case=None):
        self._fn = fn
        self.reads = frozenset(reads)
        self._case = case

    def value(self, row):
        return self._fn(row)

    def __bool__(self):
        raise ValueError(
            "Cannot convert column into bool: please use '&' for 'and', '|' for 'or', "
            "'~' for 'not' when building DataFrame boolean expressions.")

    def __neg__(self):
        return _unary(self, operator.neg)

    def __invert__(self):
        return _unary(self, lambda v: not _boolean(v))

    def __and__(self, other):
        return _binary(self, other, _and)

    def __rand__(self, other):
        return _binary(other, self, _and)

    def __or__(self, other):
        return _binary(self, other, _or)

    def __ror__(self, other):
        return _binary(other, self, _or)

    def isNull(self):
        return Col(lambda row: self._fn(row) is None, self.reads)

    def isNotNull(self):
        return Col(lambda row: self._fn(row) is not None, self.reads)

    def cast(self, data_type):
        convert = _CASTS.get(data_type) if isinstance(data_type, str) else None
        if convert is None:
            raise TypeError(f'cast type {data_type!r} is not modelled')
        return _unary(self, convert)

    def contains(self, other):
        return _text_test(self, other, lambda a, b: b in a)

    def startswith(self, other):
        return _text_test(self, other, lambda a, b: a.startswith(b))

    def endswith(self, other):
        return _text_test(self, other, lambda a, b: a.endswith(b))

    def substr(self, start, length):
        if isinstance(start, Col) != isinstance(length, Col):
            raise TypeError('startPos and length must be the same type')
        return _binary_op3(self, start, length, _substring_sql)

    def isin(self, *values):
        if len(values) == 1 and isinstance(values[0], (list, tuple, set)):
            values = tuple(values[0])
        return _unary(self, lambda v: v in values)

    def getItem(self, key):
        if not isinstance(key, int) or isinstance(key, bool):
            raise TypeError('getItem key must be an integer')
        return _unary(self, lambda items: items[key] if 0 <= key < len(items) else None)

    def when(self, condition, value):
        if self._case is None or self._case.closed:
            raise ValueError('when() can only be applied on a Column previously '
                             'generated by when(), before otherwise()')
        return _case(self._case.branches + [_branch(condition, value)], None)

    def otherwise(self, value):
        if self._case is None or self._case.closed:
            raise ValueError('otherwise() can only be applied once, on a Column '
                             'previously generated by when()')
        return _case(self._case.branches, _operand(value))


# ── Helpers ────────────────────────────────────────────────────────

def _operand(value):
    """Return ``(fn, reads)`` for a Column or for a Python literal."""
    if isinstance(value, Col):
        return value._fn, value.reads
    return (lambda row: value), frozenset()


def _unary(col, fn):
    def run(row):
        value = col._fn(row)
        return None if value is None else fn(value)
    return Col(run, col.reads)


def _binary(left, right, op):
    left_fn, left_reads = _operand(left)
    right_fn, right_reads = _operand(right)
    return Col(lambda row: op(left_fn(row), right_fn(row)), left_reads | right_reads)


def _binary_op3(col, first, second, op):
    first_fn, first_reads = _operand(first)
    second_fn, second_reads = _operand(second)

    def run(row):
        values = (col._fn(row), first_fn(row), second_fn(row))
        return None if any(v is None for v in values) else op(*values)

    return Col(run, col.reads | first_reads | second_reads)


def _boolean(value):
    if value is not None and not isinstance(value, bool):
        raise TypeError(f'a boolean operand is required, got {value!r}')
    return value


def _and(left, right):
    left, right = _boolean(left), _boolean(right)
    if left is False or right is False:
        return False
    return None if left is None or right is None else True


def _or(left, right):
    left, right = _boolean(left), _boolean(right)
    if left is True or right is True:
        return True
    return None if left is None or right is None else False


def _number(value):
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise TypeError(f'arithmetic needs numbers, got {value!r}')
    return value


def _text(value):
    if not isinstance(value, str):
        raise TypeError(f'a string is required, got {value!r}')
    return value


def _division(left, right):
    return None if right == 0 else left / right


def _remainder(left, right):
    if right == 0:
        return None
    result = math.fmod(left, right)
    return int(result) if isinstance(left, int) and isinstance(right, int) else result


def _arithmetic(fn):
    def op(left, right):
        if left is None or right is None:
            return None
        return fn(_number(left), _number(right))
    return op


def _kind(value):
    if isinstance(value, bool):
        return 'boolean'
    if isinstance(value, (int, float)):
        return 'number'
    if isinstance(value, str):
        return 'string'
    return 'datetime' if isinstance(value, dt.datetime) else 'date'


def _comparison(fn):
    def op(left, right):
        if left is None or right is None:
            return None
        if {_kind(left), _kind(right)} == {'date', 'datetime'}:
            left, right = _as_datetime(left), _as_datetime(right)
        elif _kind(left) != _kind(right):
            raise TypeError(f'cannot compare {left!r} with {right!r}')
        return fn(left, right)
    return op


for _name, _fn in (('add', operator.add), ('sub', operator.sub), ('mul', operator.mul),
                   ('truediv', _division), ('mod', _remainder)):
    setattr(Col, f'__{_name}__',
            lambda self, other, _fn=_fn: _binary(self, other, _arithmetic(_fn)))
    setattr(Col, f'__r{_name}__',
            lambda self, other, _fn=_fn: _binary(other, self, _arithmetic(_fn)))

for _name, _fn in (('eq', operator.eq), ('ne', operator.ne), ('lt', operator.lt),
                   ('le', operator.le), ('gt', operator.gt), ('ge', operator.ge)):
    setattr(Col, f'__{_name}__',
            lambda self, other, _fn=_fn: _binary(self, other, _comparison(_fn)))
Col.__hash__ = object.__hash__


def _branch(condition, value):
    if not isinstance(condition, Col):
        raise TypeError('the condition of when() must be a Column')
    return (condition, *_operand(value))


def _case(branches, otherwise):
    reads = frozenset()
    for condition, _, value_reads in branches:
        reads |= condition.reads | value_reads
    if otherwise is not None:
        reads |= otherwise[1]

    def run(row):
        for condition, value_fn, _ in branches:
            if condition._fn(row) is True:
                return value_fn(row)
        return otherwise[0](row) if otherwise is not None else None

    return Col(run, reads, _Case(list(branches), otherwise is not None))


def _text_test(col, other, test):
    if not isinstance(other, (Col, str)):
        raise TypeError('contains/startswith/endswith take a Column or a string')
    return _binary(col, other, lambda a, b: None if a is None or b is None
                   else test(_text(a), _text(b)))


def _substring_sql(text, pos, length):
    """Spark ``UTF8String.substringSQL``: one-based, zero and negative positions allowed."""
    text = _text(text)
    size = len(text)
    start = pos - 1 if pos > 0 else (size + pos if pos < 0 else 0)
    end = start + length
    start = max(start, 0)
    if end <= start or start >= size:
        return ''
    return text[start:end]


def _as_date(value):
    if isinstance(value, dt.datetime):
        return value.date()
    if isinstance(value, dt.date):
        return value
    if isinstance(value, str):
        try:
            return dt.date.fromisoformat(value.strip()[:10])
        except ValueError:
            return None
    raise TypeError(f'a date is required, got {value!r}')


def _as_datetime(value):
    if isinstance(value, dt.datetime):
        return value
    if isinstance(value, dt.date):
        return dt.datetime(value.year, value.month, value.day)
    if isinstance(value, str):
        try:
            return dt.datetime.fromisoformat(value.strip())
        except ValueError:
            return None
    raise TypeError(f'a timestamp is required, got {value!r}')


def _to_long(value):
    if isinstance(value, str):
        try:
            return int(Decimal(value.strip()))
        except (InvalidOperation, ValueError):
            return None
    if isinstance(value, float) and not math.isfinite(value):
        return 0 if math.isnan(value) else None
    return int(value)


def _to_string(value):
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, dt.datetime):
        return value.isoformat(sep=' ')
    if isinstance(value, dt.date):
        return value.isoformat()
    return value if isinstance(value, str) else str(value)


_CASTS = {'long': _to_long, 'double': float, 'string': _to_string}


def _round_half_up(value, scale):
    if isinstance(value, float) and not math.isfinite(value):
        return value
    if isinstance(value, int) and scale >= 0:
        return value
    exact = Decimal(repr(value)) if isinstance(value, float) else Decimal(value)
    rounded = exact.quantize(Decimal(1).scaleb(-scale), rounding=ROUND_HALF_UP)
    return float(rounded) if isinstance(value, float) else int(rounded)


def _power(base, exponent):
    try:
        return math.pow(base, exponent)
    except OverflowError:
        return math.inf
    except ValueError:
        return NAN if base < 0 else math.inf


def _java_replacement(match, template):
    """Expand a Java ``Matcher`` replacement: ``\\x`` is a literal, ``$n`` a group."""
    out, i = [], 0
    while i < len(template):
        char = template[i]
        i += 1
        if char == '\\':
            if i >= len(template):
                raise ValueError('character to be escaped is missing')
            out.append(template[i])
            i += 1
        elif char == '$':
            if i >= len(template) or not template[i].isdigit():
                raise ValueError('illegal group reference')
            number = int(template[i])
            i += 1
            while (i < len(template) and template[i].isdigit()
                   and number * 10 + int(template[i]) <= match.re.groups):
                number = number * 10 + int(template[i])
                i += 1
            if number > match.re.groups:
                raise IndexError(f'no group {number}')
            out.append(match.group(number) or '')
        else:
            out.append(char)
    return ''.join(out)


def _quarter_start(day):
    return dt.date(day.year, 3 * ((day.month - 1) // 3) + 1, 1)


# ── pyspark.sql.functions ──────────────────────────────────────────

class _Functions:
    """The ``F`` namespace: one method per function the converter may emit."""

    @staticmethod
    def _c(value):
        if isinstance(value, Col):
            return value
        if isinstance(value, str):
            return F.col(value)
        raise TypeError(f'a Column or a column name is required, got {value!r}')

    @staticmethod
    def col(name):
        if not isinstance(name, str):
            raise TypeError('a column name must be a string')
        return Col(lambda row: row.get(name), {name})

    @staticmethod
    def lit(value):
        return value if isinstance(value, Col) else Col(lambda row: value)

    @staticmethod
    def when(condition, value):
        return _case([_branch(condition, value)], None)

    def coalesce(self, *cols):
        cols = [self._c(c) for c in cols]

        def run(row):
            for c in cols:
                value = c._fn(row)
                if value is not None:
                    return value
            return None

        return Col(run, frozenset().union(*(c.reads for c in cols)))

    def concat(self, *cols):
        cols = [self._c(c) for c in cols]

        def run(row):
            values = [c._fn(row) for c in cols]
            return None if any(v is None for v in values) else ''.join(_text(v) for v in values)

        return Col(run, frozenset().union(*(c.reads for c in cols)))

    def _math(self, col, fn):
        return _unary(self._c(col), fn)

    def abs(self, col):
        return self._math(col, abs)

    def sqrt(self, col):
        return self._math(col, lambda v: math.sqrt(v) if v >= 0 else NAN)

    def exp(self, col):
        return self._math(col, lambda v: math.exp(v) if v < 700 else math.inf)

    def sin(self, col):
        return self._math(col, math.sin)

    def cos(self, col):
        return self._math(col, math.cos)

    def tan(self, col):
        return self._math(col, math.tan)

    def asin(self, col):
        return self._math(col, lambda v: math.asin(v) if -1 <= v <= 1 else NAN)

    def acos(self, col):
        return self._math(col, lambda v: math.acos(v) if -1 <= v <= 1 else NAN)

    def atan(self, col):
        return self._math(col, math.atan)

    def degrees(self, col):
        return self._math(col, math.degrees)

    def radians(self, col):
        return self._math(col, math.radians)

    def floor(self, col):
        return self._math(col, math.floor)

    def ceil(self, col):
        return self._math(col, math.ceil)

    def log10(self, col):
        return self._math(col, lambda v: math.log10(v) if v > 0 else None)

    def log(self, arg1, arg2=None):
        if arg2 is None:
            return self._math(arg1, lambda v: math.log(v) if v > 0 else None)
        if isinstance(arg1, Col) or not isinstance(arg1, float):
            raise TypeError('the base of log() must be a float literal')
        return self._math(arg2, lambda v: math.log(v, arg1) if v > 0 else None)

    def pow(self, base, exponent):
        left, right = self._c(base), self._c(exponent)
        return _binary(left, right, lambda a, b: None if a is None or b is None
                       else _power(_number(a), _number(b)))

    def round(self, col, scale=0):
        if not isinstance(scale, int) or isinstance(scale, bool):
            raise TypeError('the scale of round() must be an integer')
        return self._math(col, lambda v: _round_half_up(_number(v), scale))

    def to_date(self, col):
        return self._math(col, _as_date)

    def to_timestamp(self, col):
        return self._math(col, _as_datetime)

    def upper(self, col):
        return self._math(col, lambda v: _text(v).upper())

    def lower(self, col):
        return self._math(col, lambda v: _text(v).lower())

    def trim(self, col):
        return self._math(col, lambda v: _text(v).strip(' '))

    def ltrim(self, col):
        return self._math(col, lambda v: _text(v).lstrip(' '))

    def rtrim(self, col):
        return self._math(col, lambda v: _text(v).rstrip(' '))

    def length(self, col):
        return self._math(col, lambda v: len(_text(v)))

    def regexp_replace(self, col, pattern, replacement):
        if not isinstance(pattern, str) or not isinstance(replacement, str):
            raise TypeError('the pattern and the replacement must be string literals')
        regex = re.compile(pattern)
        return self._math(col, lambda v: regex.sub(
            lambda match: _java_replacement(match, replacement), _text(v)))

    def locate(self, substr, col, pos=1):
        if not isinstance(substr, str) or not isinstance(pos, int):
            raise TypeError('locate() takes a string literal and an integer position')
        return self._math(col, lambda v: _text(v).find(substr, pos - 1) + 1)

    def split(self, col, pattern, limit=-1):
        if not isinstance(pattern, str):
            raise TypeError('the pattern of split() must be a string literal')
        regex = re.compile(pattern)
        return self._math(col, lambda v: regex.split(_text(v)))

    @staticmethod
    def current_date():
        return Col(lambda row: TODAY)

    @staticmethod
    def current_timestamp():
        return Col(lambda row: NOW)

    def _part(self, col, fn, use_time=False):
        convert = _as_datetime if use_time else _as_date
        return self._math(col, lambda v: None if (d := convert(v)) is None else fn(d))

    def year(self, col):
        return self._part(col, lambda d: d.year)

    def month(self, col):
        return self._part(col, lambda d: d.month)

    def dayofmonth(self, col):
        return self._part(col, lambda d: d.day)

    def quarter(self, col):
        return self._part(col, lambda d: (d.month - 1) // 3 + 1)

    def dayofyear(self, col):
        return self._part(col, lambda d: d.timetuple().tm_yday)

    def hour(self, col):
        return self._part(col, lambda d: d.hour, use_time=True)

    def minute(self, col):
        return self._part(col, lambda d: d.minute, use_time=True)

    def second(self, col):
        return self._part(col, lambda d: d.second, use_time=True)

    def datediff(self, end, start):
        return _binary(self._c(end), self._c(start), lambda a, b: None
                       if a is None or b is None else (_as_date(a) - _as_date(b)).days)

    def trunc(self, col, format):
        starts = {'year': lambda d: dt.date(d.year, 1, 1),
                  'quarter': _quarter_start,
                  'month': lambda d: dt.date(d.year, d.month, 1)}
        if format not in starts:
            raise TypeError(f'trunc() format {format!r} is not modelled')
        return self._part(col, starts[format])

    def date_trunc(self, format, col):
        starts = {
            'year': lambda t: dt.datetime(t.year, 1, 1),
            'quarter': lambda t: dt.datetime.combine(_quarter_start(t), dt.time()),
            'month': lambda t: dt.datetime(t.year, t.month, 1),
            'day': lambda t: dt.datetime(t.year, t.month, t.day),
            'hour': lambda t: t.replace(minute=0, second=0, microsecond=0),
            'minute': lambda t: t.replace(second=0, microsecond=0),
            'second': lambda t: t.replace(microsecond=0),
        }
        if not isinstance(format, str) or format not in starts:
            raise TypeError(f'date_trunc() format {format!r} is not modelled')
        return self._part(col, starts[format], use_time=True)


F = _Functions()


# ── Running generated code ─────────────────────────────────────────

class Frame:
    """Stands for ``df``: records ``withColumn`` calls and type-checks their arguments."""

    def __init__(self):
        self.columns = []

    def withColumn(self, name, col):
        if not isinstance(name, str):
            raise TypeError('the column name must be a string')
        if not isinstance(col, Col):
            raise TypeError('col should be Column')
        self.columns.append((name, col))
        return self


def build(expression):
    """Evaluate a generated expression to a :class:`Col`, raising as PySpark would."""
    result = eval(expression, {'F': F, '__builtins__': {}})
    if not isinstance(result, Col):
        raise TypeError(f'expected a Column, got {type(result).__name__}')
    return result


def evaluate(expression, row):
    """Return the value of ``expression`` for one row (a dict; NULL is ``None``)."""
    return build(expression).value(Row(row))


def run_statement(statement, row):
    """Run a ``df = df.withColumn(...)`` statement; return ``(name, value)``."""
    frame = Frame()
    exec(statement, {'F': F, 'df': frame, '__builtins__': {}})
    ((name, col),) = frame.columns
    return name, col.value(Row(row))
